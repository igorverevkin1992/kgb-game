/**
 * Диегетические сигналы: как шкалы риска видны на столе без цифр (GDD, Блок 3:
 * «число отметок SOG на карте, тон резолюций Центра, банковские уведомления»).
 */

/** Сколько красных отметок наружки видно на карте: каждые 20% шкалы SOG Heat — одна отметка. */
export const sogMarks = (sogHeat: number) => Math.min(5, Math.floor(sogHeat / 20));
